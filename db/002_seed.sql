-- ------------------------------------------------------------
-- 팀 8개 (각 정원 10명)
-- ------------------------------------------------------------
-- generate_series(1, 8) 은 1부터 8까지 숫자를 한 줄씩 만들어준다.
-- 여덟 줄을 손으로 쓰는 대신 이 한 줄로 끝낸다.
INSERT INTO "goldenbell-teams" (name, max_members, sort_order)
SELECT n || '팀', 10, n
FROM generate_series(1, 8) AS n
ON CONFLICT (name) DO NOTHING;


-- ------------------------------------------------------------
-- 문제와 정답
-- ------------------------------------------------------------
-- 여기 있던 테스트 문제 5개는 폐기했다.
-- 실제 행사 문제 48개는 006_questions.sql 에 들어 있다.
--
-- 문제를 이 파일에 두지 않는 이유:
-- 문제를 고칠 때마다 이 파일을 건드리면 팀 목록까지 같이 흔들린다.
-- 자주 바뀌는 것(문제)과 안 바뀌는 것(팀)을 파일로 갈라두면
-- 문제만 다시 넣고 싶을 때 006 만 보면 된다.


-- ------------------------------------------------------------
-- 진행자 계정
-- ------------------------------------------------------------
-- 비밀번호는 여기에 넣지 않는다. 원문이 파일에 남으면 그대로 유출된다.
-- 계정 만들기는 아래 명령으로 한다. 비밀번호를 물어보고 변환해서 저장한다.
--
--     npm run create-admin
