SELECT
  (SELECT count(*) FROM "goldenbell-teams")       AS 팀,
  (SELECT count(*) FROM "goldenbell-quizz")       AS 문제,
  (SELECT count(*) FROM "goldenbell-answer-keys") AS 정답,
  (SELECT count(*) FROM "goldenbell-admin")       AS 진행자;
